def fmt(r):
    doi = f"  doi:{r['doi']}" if r["doi"] else ""
    return (f"{r['title']}. {r['journal']}. {r['pubdate']}. "
            f"PMID: {r['pmid']}.{doi}")


def main():
    md, flat, missing = [], [], []
    md.append("# 外科的心房細動治療の最新動向 — 文献リスト（DL用）\n")
    md.append("PubMed 5,051件から絞り込んだ精読候補。★=必読 / ○=推奨。\n")
    md.append("PMID 一括DL: PubMed の検索窓に末尾の「一括PMIDリスト」を貼り付け → Send to → Citation manager\n")
    n1 = n2 = 0
    for sid, title, items in SECTIONS:
        md.append(f"\n---\n\n## {sid}. {title}\n")
        for pmid, prio, note in items:
            r = recs.get(pmid)
            if not r:
                missing.append(pmid)
                continue
            mark = "★" if prio == 1 else "○"
            if prio == 1:
                n1 += 1
            else:
                n2 += 1
            md.append(f"- {mark} **{r['title']}**  ")
            md.append(f"  {r['journal']}. {r['pubdate']}. "
                      f"**PMID: {r['pmid']}**"
                      + (f" / doi: {r['doi']}" if r["doi"] else "") + "  ")
            md.append(f"  <sub>{note}</sub>")
            flat.append(pmid)

    md.append("\n---\n\n## 一括PMIDリスト（PubMedにそのまま貼り付け可）\n")
    md.append("```")
    for i in range(0, len(flat), 10):
        md.append(" ".join(flat[i:i + 10]))
    md.append("```\n")
    md.append(f"\n合計 {len(flat)} 編（★必読 {n1} / ○推奨 {n2}）\n")

    path = os.path.join(HERE, "md", "reading_list.md")
    open(path, "w").write("\n".join(md))
    open(os.path.join(HERE, "corpus", "pmid_list.txt"), "w").write(
        " ".join(flat) + "\n")
    print(f"wrote {path}: {len(flat)} papers (★{n1} ○{n2})")
    if missing:
        print("MISSING from corpus:", missing)


if __name__ == "__main__":
    main()
